/*
 * The OLED's font: misc-fixed 5x8, public domain (font_5x8.c, generated by tools/font/pcf2c.py). In a 6 x 8 cell,
 * 21 columns on a 128-pixel-wide OLED, and a text row to each 8-pixel page.
 */
#ifndef RMFE_PICO_FONT_5X8_H
#define RMFE_PICO_FONT_5X8_H

#include <stdint.h>

#define FONT_5X8_WIDTH  5
#define FONT_5X8_HEIGHT 8
#define FONT_5X8_FIRST  0x20
#define FONT_5X8_LAST   0x7E

/* Glyph rows for characters FONT_5X8_FIRST..FONT_5X8_LAST: one byte a row from the top, leftmost pixel in bit 7. */
extern const uint8_t font_5x8_glyphs[FONT_5X8_LAST - FONT_5X8_FIRST + 1][FONT_5X8_HEIGHT];

#endif
