"""Turn an X11 fixed-width bitmap font (.pcf or .pcf.gz) into the C table the display uses (src/pico/font_8x13.c).

usage: pcf2c.py FONT.pcf[.gz] > src/pico/font_8x13.c

Made for the misc-fixed 8x13 font (xfonts-base: /usr/share/fonts/X11/misc/8x13-ISO8859-1.pcf.gz), which is public
domain ("Public domain font. Share and enjoy.", its COPYRIGHT property). The script refuses a font that doesn't say
so, or isn't 8 pixels wide. Characters 0x20-0x7E, 13 bytes each, one byte a row from the top, the leftmost pixel in
bit 7. Needs Pillow.
"""
import gzip
import sys

from PIL import PcfFontFile

WIDTH, HEIGHT, ASCENT = 8, 13, 11
FIRST, LAST = 0x20, 0x7E


def main():
    path = sys.argv[1]
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rb") as fp:
        font = PcfFontFile.PcfFontFile(fp)
        props = font._load_properties()
    if props.get(b"COPYRIGHT") != b"Public domain font.  Share and enjoy.":
        sys.exit(f"{path}: not marked public domain: {props.get(b'COPYRIGHT')}")
    rows = []
    for ch in range(FIRST, LAST + 1):
        glyph = font.glyph[ch]
        if glyph is None:
            sys.exit(f"{path}: no glyph for {ch:#04x}")
        (dwidth, _), (x0, y0, x1, y1), _, im = glyph
        if dwidth != WIDTH:
            sys.exit(f"{path}: {ch:#04x} is {dwidth} pixels wide, not {WIDTH}")
        cell = [0] * HEIGHT
        for y in range(y1 - y0):
            for x in range(x1 - x0):
                if im.getpixel((x, y)):
                    cell[y + y0 + ASCENT] |= 0x80 >> (x + x0)
        rows.append((ch, cell))

    print(f"""/*
 * The misc-fixed 8x13 font (X11, xfonts-base), characters 0x20-0x7E. Public domain: "Public domain font.
 * Share and enjoy." Generated by tools/font/pcf2c.py from {props.get(b'FONT', b'').decode()};
 * don't edit it by hand. One byte a row from the top, the leftmost pixel in bit 7. The rest of this repository
 * is GPL-3.0-or-later; this table is public domain.
 */
#include "pico/font_8x13.h"

const uint8_t font_8x13_glyphs[FONT_8X13_LAST - FONT_8X13_FIRST + 1][FONT_8X13_HEIGHT] = {{""")
    for ch, cell in rows:
        shown = chr(ch) if ch not in (0x5C,) else "backslash"
        print("    {" + ", ".join(f"0x{b:02x}" for b in cell) + f"}}, /* {ch:02x} {shown} */")
    print("};")


if __name__ == "__main__":
    main()
