"""Turn an X11 fixed-width bitmap font (.pcf or .pcf.gz) into a C table for the displays (src/pico/font_*.c).

usage: pcf2c.py FONT.pcf[.gz] > src/pico/font_WxH.c
       pcf2c.py FONT.pcf[.gz] --header > src/pico/font_WxH.h
       then clang-format -i both (it wraps the longer rows and comments)

Made for the misc-fixed fonts (xfonts-base, /usr/share/fonts/X11/misc/): 8x13-ISO8859-1 for the TFT
(src/pico/font_8x13.c), and 5x8 and others for the OLED. They are public domain ("Public domain font.  Share and
enjoy.", or "Public domain terminal emulator font.  Share and enjoy.", their COPYRIGHT property). The script refuses
a font that doesn't say so, isn't fixed width, or is wider than 16 pixels. The cell is the font's width by its ascent
plus descent; the name is font_WxH, with a "b" after it for a bold font. Characters 0x20-0x7E, H rows each from the
top: up to 8 pixels wide a row is a byte, the leftmost pixel in bit 7; wider, a uint16_t, the leftmost in bit 15.
Needs Pillow.
"""
import gzip
import sys

from PIL import PcfFontFile

FIRST, LAST = 0x20, 0x7E
PUBLIC_DOMAIN = (b"Public domain font.  Share and enjoy.", b"Public domain terminal emulator font.  Share and enjoy.")


def main():
    if len(sys.argv) not in (2, 3) or (len(sys.argv) == 3 and sys.argv[2] != "--header"):
        sys.exit(__doc__)
    path = sys.argv[1]
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rb") as fp:
        font = PcfFontFile.PcfFontFile(fp)
        props = font._load_properties()
    if props.get(b"COPYRIGHT") not in PUBLIC_DOMAIN:
        sys.exit(f"{path}: not marked public domain: {props.get(b'COPYRIGHT')}")
    glyphs = [font.glyph[ch] for ch in range(FIRST, LAST + 1)]
    for ch, glyph in zip(range(FIRST, LAST + 1), glyphs):
        if glyph is None:
            sys.exit(f"{path}: no glyph for {ch:#04x}")
    width = glyphs[0][0][0]
    ascent = max(-g[1][1] for g in glyphs)
    height = ascent + max(g[1][3] for g in glyphs)
    if width > 16:
        sys.exit(f"{path}: {width} pixels wide; a row is 16 bits at most")
    bits = 8 if width <= 8 else 16
    rows = []
    for ch, glyph in zip(range(FIRST, LAST + 1), glyphs):
        (dwidth, _), (x0, y0, x1, y1), _, im = glyph
        if dwidth != width:
            sys.exit(f"{path}: {ch:#04x} is {dwidth} pixels wide, not {width}")
        cell = [0] * height
        for y in range(y1 - y0):
            for x in range(x1 - x0):
                if im.getpixel((x, y)):
                    cell[y + y0 + ascent] |= (1 << (bits - 1)) >> (x + x0)
        rows.append((ch, cell))

    xlfd = props.get(b"FONT", b"").decode()
    bold = xlfd.split("-")[3].lower() == "bold" if xlfd.count("-") > 3 else False
    size = f"{width}x{height}" + ("b" if bold else "")
    name, macro, kind = f"font_{size}", f"FONT_{size.upper()}", f"uint{bits}_t"
    described = f"misc-fixed {width}x{height}" + (" bold" if bold else "")
    if len(sys.argv) == 3:
        guard = f"RMFE_PICO_FONT_{size.upper()}_H"
        print(f"""{LICENCE}
/*
 * The {described} font, public domain ({name}.c, generated by tools/font/pcf2c.py --header; don't edit it
 * by hand).
 */
#ifndef {guard}
#define {guard}

#include <stdint.h>

#define {macro}_WIDTH  {width}
#define {macro}_HEIGHT {height}
#define {macro}_FIRST  0x{FIRST:02X}
#define {macro}_LAST   0x{LAST:02X}

/* Glyph rows for characters {macro}_FIRST..{macro}_LAST: one a row from the top, leftmost pixel in bit {bits - 1}. */
extern const {kind} {name}_glyphs[{macro}_LAST - {macro}_FIRST + 1][{macro}_HEIGHT];

#endif""")
        return

    unit = "byte" if bits == 8 else "uint16_t"
    print(f"""/*
 * The {described} font (X11, xfonts-base), characters 0x20-0x7E. Public domain: "{props[b'COPYRIGHT'].decode()[:-18]}
 * Share and enjoy." Generated by tools/font/pcf2c.py from {xlfd};
 * don't edit it by hand. One {unit} a row from the top, the leftmost pixel in bit {bits - 1}. The rest of this repository
 * is GPL-3.0-or-later; this table is public domain.
 */
#include "pico/{name}.h"

const {kind} {name}_glyphs[{macro}_LAST - {macro}_FIRST + 1][{macro}_HEIGHT] = {{""")
    digits = 2 if bits == 8 else 4
    for ch, cell in rows:
        shown = chr(ch) if ch not in (0x5C,) else "backslash"
        print("    {" + ", ".join(f"0x{b:0{digits}x}" for b in cell) + f"}}, /* {ch:02x} {shown} */")
    print("};")


